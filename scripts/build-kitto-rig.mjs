// Converts the Kitto front rig SVG into a TypeScript module the avatar can render.
//   node scripts/build-kitto-rig.mjs
// - prefixes every id (and url(#...) / href references) with __K__ so each
//   rendered instance can swap in a unique prefix
// - tags pupils (small dark ellipses inside eyes_* groups) with class="kitto-pupil"
//   so they can follow the cursor
import { readFileSync, writeFileSync } from "node:fs";

const SRC = "design/kitto-kit-v3/rigs/kitto_front_rig.svg";
const OUT = "components/kitto/rig.generated.ts";

const svg = readFileSync(SRC, "utf8");
const viewBox = /viewBox="([^"]+)"/.exec(svg)[1];
let inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");

inner = inner
  .replace(/\sid="([^"]+)"/g, ' id="__K__$1"')
  .replace(/url\(#([^)]+)\)/g, "url(#__K__$1)")
  .replace(/href="#([^"]+)"/g, 'href="#__K__$1"');

// Pupils: dark ellipses inside eye groups.
inner = inner.replace(/(<g id="__K__eyes_[a-z_]+"[\s\S]*?<\/g>)/g, (group) =>
  group.replace(/<ellipse([^>]*fill="#0B0B0F"[^>]*)\/>/g, '<ellipse class="kitto-pupil"$1/>'),
);

if (/<script|javascript:|\son[a-z]+=/i.test(inner)) throw new Error("Rig contains script content; refusing to embed.");

writeFileSync(
  OUT,
  `// Generated by scripts/build-kitto-rig.mjs from ${SRC}. Do not edit by hand.\n` +
    `export const RIG_VIEWBOX = ${JSON.stringify(viewBox)};\n` +
    `export const RIG_MARKUP = ${JSON.stringify(inner)};\n`,
);
console.log(`wrote ${OUT} (${inner.length} chars, ${(inner.match(/kitto-pupil/g) || []).length} pupils)`);
